pub fn translate_dynamic(en: String) -> String {
    if let Some(rest) = en.strip_prefix("Last read: ") {
        return format!("Son okuma: {rest}");
    }
    if let Some(rest) = en.strip_prefix("no change (") {
        return format!("değişiklik yok ({rest}");
    }
    if let Some(rest) = en.strip_prefix("updated (") {
        return format!("güncellendi ({rest}");
    }
    if let Some(rest) = en.strip_prefix("Read ") {
        if let Some(n) = rest.strip_suffix(" of 17 gauges.") {
            return format!("17 göstergeden {n} tanesi okundu.");
        }
    }
    if let Some(rest) = en.strip_prefix("Training ") {
        return format!("Antrenman {rest}");
    }
    en
}
